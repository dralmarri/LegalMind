"""إعادةُ فحصٍ للنسخة المنشورة — لا تنشر شيئًا ولا تمسّ القاعدة.
التأكيدُ المصحَّح: المطلوبُ ألّا تحتلّ م12 مكرر موضعًا **في مخرَج محفّز الاختصاص** (وقد امتنعت)،
لا أن تختفي من الثمانية عشر كلِّها — فعودتُها من حِزم الفرع العامة في الموضع الأخير سلوكٌ سليم."""
import sys
sys.path.insert(0, "/opt/LegalMind")
from admin import app as m

HI = 18
B = lambda q: list(m._draft_bundles("استشارة", q, [], None, None))


def need(b, oid, lbl):
    i = b.index(oid) if oid in b else None
    assert i is not None and i < HI, "%s: %s خارج النافذة (موضع %s)" % (lbl, oid, i)
    return i


q = ("شركتي وقّعت عقد توريد مع وزارة الأشغال العامة، ونفّذنا 80% من الكمّيات، ثمّ أوقفت الوزارة "
     "الصرف وأنذرتنا بسحب العمل. أين أرفع دعواي؟ وما المواعيد؟ وهل أستطيع وقف قرار السحب؟")
b = B(q)
# التأكيدُ المصحَّح: المحفّزُ نفسُه لا يُصدِر م12 مكرر
vids = m._venue_ids(m._draft_norm_ar(q))
assert "legis-20-1981-m12mkr" not in vids, "المحفّزُ ما زال يُصدر م12 مكرر"
print("✓ محفّزُ الاختصاص يُصدر %d معرّفًا، ليس فيها م12 مكرر" % len(vids))
print("  المواضع 0-16: %s" % ", ".join(o.replace("legis-", "") for o in b[:17]))
i = b.index("legis-20-1981-m12mkr") if "legis-20-1981-m12mkr" in b else None
print("  م12 مكرر (من حِزم الفرع العامة) ⇐ موضع %s — خارج نطاق المحفّز" % i)

print("\n== فحوصُ عدم الانحدار التي لم تُنفَّذ ==")
for qq, lbl in (("أي محكمة تختص بدعوى تعويض ضد وزارة الصحة عن خطأ طبي أصابني؟", "خطأ طبّيّ"),
                ("أي محكمة تختص بدعوى صحة ونفاذ عقد بيع عقار قيمته مائة ألف دينار؟", "بيعُ عقار")):
    bb = B(qq)
    k = [j for j, o in enumerate(bb) if o == "legis-38-1980-m34"]
    assert k and k[0] < HI, "%s: م34 مرافعات خارج النافذة (%s)" % (lbl, k[:1])
    print("  ✓ %-10s م34 مرافعات موضع %d — لم يُحوَّل إلى الإداريّ" % (lbl, k[0]))

b3 = B("بعتُ نصيبي في قسيمةٍ سكنية بتوقيعٍ إلكترونيّ وأنكر المشتري، هل انتقلت الملكية؟ وما دعواي؟")
for oid in ("legis-5-1959-m7", "legis-20-2014-m2", "legis-20-2014-m3"):
    need(b3, oid, "الجسرُ العقاريّ")
print("  ✓ الجسرُ العقاريُّ الإلكترونيّ سليم (م7 موضع %d)" % b3.index("legis-5-1959-m7"))

leak = [o for o in B("ما عقوبةُ السرقة من منزلٍ مسكونٍ ليلًا؟")
        if o.startswith(("legis-5-1959", "legis-38-1980-m34"))]
assert not leak, "تسرّبٌ في السؤال الجزائيّ: %s" % leak[:3]
print("  ✓ الصمتُ الواجب في السؤال الجزائيّ")

b4 = B("أنشأت شركة وأريد ترخيص موقع إخباري إلكتروني، وإذا رفضت الوزارة هل أتظلم وأي محكمة تختص؟")
assert any(o.startswith("legis-8-2016") for o in b4[:HI]), "انحدارُ عائلة الإعلام"
print("  ✓ عائلةُ الإعلام محتفظةٌ بصدارتها")
print("\n=== كلُّ الفحوص خضراء — النسخةُ المنشورة سليمة ===")
