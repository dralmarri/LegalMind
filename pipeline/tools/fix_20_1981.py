def normalize_text(text):
    try:
        sys.path.insert(0, "/opt/LegalMind/engine")
        from normalizer.canonical import normalize_text as nt
        return nt(text)
    except Exception:
        import unicodedata
        t = unicodedata.normalize("NFKC", text).replace("ـ", "")
        t = re.sub(r"[ \t]+", " ", t); t = re.sub(r" *\n *", "\n", t)
        return re.sub(r"\n{3,}", "\n\n", t).strip()


def main():
    dry = "--dry-run" in sys.argv
    import psycopg
    dsn = os.getenv("DATABASE_URL") or "postgresql://legalmind:__SET_DATABASE_URL_ENV__@127.0.0.1:55432/legalmind"
    ids = sorted({f for f, _, _, _ in FIXES})
    with psycopg.connect(dsn) as conn, conn.cursor() as cur:
        cur.execute("SELECT id,original_text FROM knowledge_objects WHERE id = ANY(%s)", (ids,))
        cur_texts = dict(cur.fetchall())
        missing = [i for i in ids if i not in cur_texts]
        if missing:
            print("خطأ: مواد غائبة عن القاعدة:", missing); return 1

        applied, skipped = [], []
        for oid, old, new, why in FIXES:
            t = cur_texts[oid]
            if old in t:
                cur_texts[oid] = t.replace(old, new)
                applied.append((oid, old, new, why))
            elif new in t:
                skipped.append((oid, old, "مطبَّقٌ سلفًا"))
            else:
                print(f"خطأ: لم يُعثر على «{old}» ولا على بديله في {oid} — أُوقف التنفيذ صيانةً للنصّ.")
                return 1

        print("== تصحيحاتُ القانون 20/1981 (مستهدَفة، حتميّة) ==")
        for oid, old, new, why in applied:
            print(f"\n• {oid}\n   «{old}»  ⇐  «{new}»\n   السند: {why}")
        for oid, old, note in skipped:
            print(f"\n• {oid}: «{old}» — {note}")
        print(f"\nالمطبَّق: {len(applied)} | المتخطَّى: {len(skipped)}")
        print("\n== مواضعُ ملتبسةٌ تُركت عمدًا بلا تعديل ==")
        for oid, note in PENDING:
            print(f"• {oid}: {note}")

        if dry:
            print("\n[dry-run] لم يُكتب شيء."); return 0

        n = 0
        for oid in ids:
            cur.execute(
                "UPDATE knowledge_objects SET original_text=%s, normalized_text=%s, updated_at=now() WHERE id=%s",
                (cur_texts[oid], normalize_text(cur_texts[oid]), oid))
            n += cur.rowcount
        conn.commit()
    print(f"\n✓ حُدّث {n} كائنًا في مكانه (لا تغيّر في العدد الإجماليّ). شغّل reindex.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
