def build_rows():
    rows = []

    def meta(extra):
        d = {"instrument": INSTRUMENT, "instrument_rank": "لائحة تنفيذية", "law_number": 106,
             "law_year": 2021, "parent_law": "20/2019", "upload_origin": "gazette_images_reg20"}
        d.update(extra); return d

    rows.append({"id": f"{REG_ID}-preamble", "topic": "الديباجة",
                 "title": "ديباجة — اللائحة التنفيذية لمكافحة الغش التجاري (قرار 106/2021)",
                 "text": PREAMBLE, "meta": meta({"chunk": "preamble"})})
    for k, (label, txt) in ISSUE.items():
        rows.append({"id": f"{REG_ID}-{k}", "topic": TOPIC,
                     "title": f"{label} — اللائحة التنفيذية لمكافحة الغش التجاري (106/2021)",
                     "text": txt, "meta": meta({"chunk": "issuance"})})
    for k, txt in ARTS.items():
        rows.append({"id": f"{REG_ID}-{k}", "topic": TOPIC,
                     "title": f"المادة {k[1:]} — اللائحة التنفيذية لمكافحة الغش التجاري (106/2021)",
                     "text": txt, "meta": meta({"article_number": k[1:]})})
    return rows


def normalize_text(text):
    try:
        sys.path.insert(0, "/opt/LegalMind/engine")
        from normalizer.canonical import normalize_text as nt
        return nt(text)
    except Exception:
        import unicodedata
        t = unicodedata.normalize("NFKC", text).replace("ـ", "")
        t = re.sub(r"[ \t]+", " ", t); t = re.sub(r" *\n *", "\n", t)
        return re.sub(r"\n{3,}", "\n\n", t).strip()


