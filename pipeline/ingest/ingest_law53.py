def build_rows():
    rows = []

    def meta(extra):
        d = {"instrument": INSTRUMENT, "instrument_rank": "مرسوم بقانون", "law_number": 53,
             "law_year": 2026, "upload_origin": "gazette_images_law53_reingest"}
        d.update(extra); return d

    pre = PREAMBLE_SUMMARY + "\n\nـــ ديباجة المرسوم بقانون (سند الإصدار) ـــ\n" + RECITALS
    rows.append({"id": f"{LAW_ID}-preamble", "branch": BRANCH, "topic": "الديباجة",
                 "title": "ديباجة المرسوم بقانون 53/2026", "text": pre, "meta": meta({"chunk": "preamble"})})
    for k, (label, txt) in ISSUE.items():
        rows.append({"id": f"{LAW_ID}-{k}", "branch": BRANCH, "topic": TOPIC,
                     "title": f"{label} — مرسوم بقانون 53/2026", "text": txt,
                     "meta": meta({"chunk": "issuance"})})
    for k, (sec, txt) in ARTS.items():
        rows.append({"id": f"{LAW_ID}-{k}", "branch": BRANCH, "topic": TOPIC,
                     "title": f"المادة {k[1:]} — {TOPIC}", "text": txt,
                     "meta": meta({"article_number": k[1:], "fasl_raw": sec})})
    return rows


def normalize_text(text):
    try:
        sys.path.insert(0, "/opt/LegalMind/engine")
        from normalizer.canonical import normalize_text as nt
        return nt(text)
    except Exception:
        import unicodedata
        t = unicodedata.normalize("NFKC", text).replace("ـ", "")
        t = re.sub(r"[ \t]+", " ", t); t = re.sub(r" *\n *", "\n", t)
        return re.sub(r"\n{3,}", "\n\n", t).strip()


