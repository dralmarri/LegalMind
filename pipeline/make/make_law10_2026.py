_AR = str.maketrans("٠١٢٣٤٥٦٧٨٩", "0123456789")


def bidi(t):
    """عكسُ اتجاه العرض يقلب القوسين حول الأرقام ويفصل الأرقامَ ويقدّم شرطةَ البند."""
    t = t.translate(_AR)
    t = re.sub(r"\)\s*(\d+(?:\s*[،,]\s*\d+)*)\s*\(", lambda m: "(%s)" % re.sub(r"\s*[،,]\s*", "، ", m.group(1).strip()), t)
    t = re.sub(r"\b(\d)\s(\d{3})\b", r"\1\2", t)          # «2 026» ⇒ «2026»
    t = re.sub(r"(?<![\d.])-(\d+)\s", r"\1- ", t)          # «-1 يخالف» ⇒ «1- يخالف»
    return re.sub(r"\s{2,}", " ", t).strip()


