def unwrap(seg):
    """الملفُّ مقطوعُ الأسطر في وسط الجُمل، فتُعاد الفقراتُ: يُوصَل السطرُ بسابقه ما لم ينتهِ
    السابقُ بعلامةِ نهايةٍ أو يبدأ الحاليُّ بعلامةِ بندٍ أو تعريفٍ (اسمٌ يليه نقطتان)."""
    BUL = re.compile(r"^(?:\d+\s*[-.)]|[أ-ي]\s*[-)]|أولًا|ثانيًا|ثالثًا|رابعًا|خامسًا|سادسًا|"
                     r"سابعًا|ثامنًا|تاسعًا|عاشرًا|أولاً|ثانياً|ثالثاً)")
    DEF = re.compile(r"^[^:]{2,60}\s:\s")            # سطرُ تعريفٍ «المتجر : …»
    out = []
    for x in (bidi(y) for y in seg if y.strip()):
        if out and not out[-1].endswith((".", ":", "؛", "،")) and not BUL.match(x) and not DEF.match(x):
            out[-1] += " " + x
        else:
            out.append(x)
    return "\n".join(out).strip()


