# ---------------------------------------------------------------- التفكيك
_PAGE = re.compile(r"^⟦ص[^⟧]*⟧$")
_NOTE = re.compile(r"^(?:###|⚠️)")
HDR = re.compile(r"^مادة (\d+)$")

lines = RAW.split("\n")
marks = [(i, int(m.group(1))) for i, x in enumerate(lines) for m in [HDR.match(x.strip())] if m]
assert [n for _, n in marks] == list(range(1, 48)), "خللٌ في تسلسل مواد اللائحة"


def clean(seg):
    out = []
    for x in seg:
        s = x.strip()
        if not s or _PAGE.match(s) or _NOTE.match(s):
            continue
        out.append(s)
    return "\n".join(out).strip()


# ديباجةُ المرسوم وبيانُ إصداره: ما قبل أوّل «مادة 1»
dec_end = next(i for i, x in enumerate(lines) if x.strip().startswith("اللائحة التنفيذية للقانون"))
decree = clean(lines[:dec_end])
sig = decree.index("أمير الكويت")
DECREE_BODY, DECREE_SIG = decree[:sig].strip(), decree[sig:].strip()

ARTS, ORDER = {}, []
for j, (s, num) in enumerate(marks):
    e = marks[j + 1][0] if j + 1 < len(marks) else len(lines)
    seg = lines[s + 1:e]
    # ترويسةُ المادة التالية تسبقها مباشرةً بلا فراغ ⇒ تُقتطع من ذيل هذه
    # وتُتخطّى علاماتُ الصفحات والملاحظات في أثناء الجمع (لا يُوقَف عندها) وإلّا انقطعت الترويسةُ
    # عن مادّتها كلّما فصلها عنها سطرُ توسيمٍ أو عبورُ صفحة.
    tail, skipped = [], []
    while seg:
        s = seg[-1].strip()
        if not s:
            break
        if _PAGE.match(s) or _NOTE.match(s):
            skipped.insert(0, seg.pop())
            continue
        tail.insert(0, seg.pop().strip())
    seg.extend(skipped)
    title_next = " / ".join(tail)          # ترويسةُ المادة التالية (تُسنَد إليها)
    ARTS[num] = {"num": num, "text": clean(seg), "_next_title": title_next}
    ORDER.append(num)

# إسنادُ الترويسات: ترويسةُ المادة n محفوظةٌ في ذيل المادة n-1
for n in ORDER:
    ARTS[n]["title"] = ARTS[n - 1]["_next_title"] if n - 1 in ARTS else ""
# ترويسةُ م1 تلي «مادة 1» لا تسبقها (صدرُ اللائحة)، فتُرفَع من المتن إلى العنوان
ARTS[1]["title"] = "التعاريف"
ARTS[1]["text"] = re.sub(r"^التعاريف\n", "", ARTS[1]["text"])
for n in ORDER:
    ARTS[n].pop("_next_title")
    ids, basis = IMPLEMENTS[n]
    for x in ids:                        # كلُّ هدفٍ يجب أن يوجد في القانون فعلًا
        assert x in LAW["articles"], "هدفٌ غيرُ موجود في القانون: م%d ⇐ %s" % (n, x)
    ARTS[n]["implements"] = ids
    ARTS[n]["implements_basis"] = basis
    if n in FILLS_GAP:
        ARTS[n]["fills_gap"] = FILLS_GAP[n]
    if n in READING_NOTE:
        ARTS[n]["reading_note"] = READING_NOTE[n]
    if n in CORRECTION:
        ARTS[n]["source_correction"] = CORRECTION[n]

data = {"decree_text": DECREE_BODY, "issuance": DECREE_SIG,
        "articles": {str(n): ARTS[n] for n in ORDER}, "order": [str(n) for n in ORDER]}
(H / "lta49_2017_parsed.json").write_text(json.dumps(data, ensure_ascii=False, indent=1),
                                          encoding="utf-8")

