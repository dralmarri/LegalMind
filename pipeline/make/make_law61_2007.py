#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""مُحوِّلُ القانون 61/2007 (الإعلام المرئي والمسموع) — 21 مادة + ديباجة.
كان الأصلُ الرقميّ شديدَ التلف (سقوطُ لامٍ وياءٍ وميمٍ وشينٍ وباءٍ في عشرات المواضع، ومحارفُ � تشطر
الكلمات، وتنوينٌ مضاعف)، فرُفض حتى وصلت صورُ الجريدة النظيفة. وكلُّ تصحيحٍ أدناه **مقروءٌ في الصور**
حرفًا بحرف — استعادةٌ لا اجتهاد. ويرفض السكربتُ التنفيذ إن بقي أثرُ تلفٍ بعد التصحيح."""
import json, pathlib, re, sys

H = pathlib.Path(__file__).parent
RAW = H / "law61_2007_raw.txt"

# ــ أوّلًا: محارفُ � التي تشطر الكلمات، والتنوينُ المضاعف، والأرقامُ المنشطرة ــ
BLOB_FIXES = [
    ("وف ق�ًا", "وفقًا"), ("وف ق�اً", "وفقًا"), ("وف ق� اً", "وفقًا"),
    ("يو م�ًا", "يومًا"), ("ت�نُشر", "تُنشر"),
    ("رقم\n5 1 لسنة 1996", "رقم 15 لسنة 1996"),
    ("قرارًًا", "قرارًا"), ("مرفوضًًا", "مرفوضًا"), ("بناءًً", "بناءً"), ("فضلاًً", "فضلًا"),
    ("مسؤولاًً", "مسؤولًا"), ("بدلاًً", "بدلًا"), ("باطلاًً", "باطلًا"), ("أسبابًًا", "أسبابًا"),
    ("وفقًًا", "وفقًا"), ("ويُُعمل", "ويُعمل"),
    # علاماتُ بنودٍ التصقت أو دخلتها شرطةٌ سفلية
    ("._10الوزير. وزير الإعلام.", "10. الوزير: وزير الإعلام."),
    ("10 -_", "10 - "), ("11 -_", "11 - "), ("12 -_", "12 - "), ("13 -_", "13 - "), ("14 -_", "14 - "),
    # علامةُ البند الأوّل في م13 سقطت وحدها بين إخوتها (الصورة تحملها)
    ("يعاقب كل منهم بما يلي:\n- بالحبس", "يعاقب كل منهم بما يلي:\n1 - بالحبس"),
]

# ــ ثانيًا: الحروفُ الساقطة — كلُّ مدخلٍ مقروءٌ في صور الجريدة ــ
WORD_FIXES = [
    ("المعني الوارد", "المعنى الوارد"), ("الإعام", "الإعلام"), ("بالمراسات", "بالمراسلات"),
    ("الأعال", "الأعمال"), ("لأعال", "لأعمال"), ("بأعال", "بأعمال"), ("أعال البث", "أعمال البث"),
    ("مها كان", "مهما كان"), ("عر الوسائل", "عبر الوسائل"), ("الردد:", "التردد:"),
    ("بالروط", "بالشروط"), ("الروط", "الشروط"), ("بروط", "بشروط"),
    ("الإعان", "الإعلان"), ("السرة", "السيرة"), ("بالرف", "بالشرف"),
    ("حاصا على", "حاصلًا على"), ("حاصا عى", "حاصلًا على"), ("خرة", "خبرة"),
    ("خال ", "خلال "), ("اثني\nعر شهرًا", "اثني\nعشر شهرًا"), ("عرة آلاف", "عشرة آلاف"),
    ("الساح", "السماح"), ("الاطاع", "الاطلاع"), ("المختصن", "المختصين"),
    ("وبتمكن موظفي", "وبتمكين موظفي"), ("بتمكن موظفي", "وبتمكين موظفي"),
    ("بتعين مدير", "بتعيين مدير"), ("الازم", "اللازم"), ("يعن بدياً", "يعين بديلًا"),
    ("هاتن العقوبتن", "هاتين العقوبتين"), ("الباد", "البلاد"), ("صى الله", "صلى الله"),
    ("السام\n-", "السلام\n-"), ("عليهم السام", "عليهم السلام"),
    ("غر مشروعة", "غير مشروعة"), ("تغير هذا النظام", "تغيير هذا النظام"),
    ("أمر الباد", "أمير البلاد"), ("الأمري", "الأميري"), ("تحقر رجال", "تحقير رجال"),
    ("التأثر في", "التأثير في"), ("إفاس التجار", "إفلاس التجار"), ("الركات التجارية", "الشركات التجارية"),
    ("اجتاع رسمي", "اجتماع رسمي"), ("حمات إعلامية", "حملات إعلامية"),
    ("القوانن", "القوانين"), ("غر صحيحة", "غير صحيحة"),
    # صورةُ الجريدة الأصلية (الكويت اليوم) تقرأ «أو التجريح» — كنظيرتها في 3/2006 م19؛
    # و«الترجيح» تصحيفٌ في النسخة المجمَّعة وفي الأصل الرقميّ معًا.
    ("أو الترجيح", "أو التجريح"),
]

# مواضعُ يتّفق عليها المصدران (الصورةُ والأصلُ الرقميّ) فلا تُمَسّ — توثيقٌ فقط:
PENDING = [
    ("م14", "«خطر أو منع بث أي إعلان» — والمعنى يقتضي «حظر»؛ الصورةُ والأصلُ متّفقان فلا تُمَسّ."),
]

SEC_RE = re.compile(r"^(فصل\s+تمهيدي\s*:?|الفصل\s+\S+\s*:?|أحكام\s+ختامية\s*:?|"
                    r"في\s+المسائل\s+المحظور\s+بثها.*)$")
ART_RE = re.compile(r"^(?:ال)?مادة\s+(\d+)\s*$")
# بقايا تلفٍ لا يجوز أن تنجو:
RESIDUE = [r"�", r"(?<![؀-ۿ])عى(?![؀-ۿ])", r"(?<![؀-ۿ])غر(?![؀-ۿ])", r"(?<![؀-ۿ])خال(?![؀-ۿ])",
           r"الإعام", r"الأعال", r"الباد", r"الروط", r"الاطاع", r"_", r"ًً", r"ُُ", r"اًً"]


def main():
    txt = RAW.read_text(encoding="utf-8")
    applied = []
    for old, new in BLOB_FIXES + WORD_FIXES:
        n = txt.count(old)
        if n:
            txt = txt.replace(old, new); applied.append((old.replace("\n", "⏎"), new.replace("\n", "⏎"), n))
    # «عى» المجرّدة ⇐ «على» (سقوطُ اللام) — بحدود الكلمة
    n = len(re.findall(r"(?<![؀-ۿ])عى(?![؀-ۿ])", txt))
    if n:
        txt = re.sub(r"(?<![؀-ۿ])عى(?![؀-ۿ])", "على", txt); applied.append(("عى", "على", n))
    for pat, rep, lbl in ((r"(?<![؀-ۿ])غر(?![؀-ۿ])", "غير", "غر"),
                          (r"(?<![؀-ۿ])خال(?![؀-ۿ])", "خلال", "خال"),
                          (r"(?<![؀-ۿ])تغير(?![؀-ۿ])", "تغيير", "تغير")):
        n = len(re.findall(pat, txt))
        if n:
            txt = re.sub(pat, rep, txt); applied.append((lbl, rep, n))
    # علاماتُ بنود التعاريف «. 1الإعلام» ⇐ «1. الإعلام»
    txt, n = re.subn(r"^\.\s*(\d{1,2})", r"\1.", txt, flags=re.M)
    if n:
        applied.append((". N", "N.", n))

    lines = txt.split("\n")
    pre_end = next(i for i, l in enumerate(lines) if l.startswith("وافق مجلس الأمة"))
    preamble = " ".join(lines[2:pre_end + 1]).strip()

    arts, order, secs = {}, [], {}
    cur, buf, pending_sec, sec = None, [], None, None
    for l in lines[pre_end + 1:]:
        s = l.strip()
        m = ART_RE.match(s)
        if m:
            if cur:
                arts[cur] = " ".join(buf).strip(); buf = []
            cur = "m" + m.group(1); order.append(cur)
            if pending_sec:
                sec = pending_sec; pending_sec = None
            secs[cur] = sec or ""
            continue
        if SEC_RE.match(s):
            pending_sec = (pending_sec + " — " + s.rstrip(":").strip()) if pending_sec else s.rstrip(":").strip()
            continue
        if cur:
            buf.append(s)
    if cur:
        arts[cur] = " ".join(buf).strip()
    for k in arts:
        arts[k] = re.sub(r"\s{2,}", " ", arts[k]).strip()

    nums = [int(k[1:]) for k in order]
    assert nums == list(range(1, 22)), "تسلسلٌ مكسور: %r" % nums
    blob = " ".join(arts.values()) + " " + preamble
    bad = [p for p in RESIDUE if re.search(p, blob)]
    assert not bad, "بقايا تلف: %s" % bad
    empty = [k for k, v in arts.items() if len(v) < 15]
    assert not empty, "موادُّ فارغة: %s" % empty

    data = {"preamble_text": preamble, "order": order, "articles": arts, "sections": secs}
    (H / "law61_2007_parsed.json").write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")

    print("== القانون 61/2007 (الإعلام المرئي والمسموع) ==")
    print("المواد: %d (1-21 متسلسلة) | الديباجة: %d حرفًا" % (len(order), len(preamble)))
    print("\n== التصحيحات المطبَّقة (%d نوعًا) — كلُّها مقروءةٌ في صور الجريدة ==" % len(applied))
    for old, new, n in applied:
        print("  • «%s» ⇐ «%s»  ×%d" % (old[:34], new[:34], n))
    print("\n== مواضعُ يتّفق عليها المصدران فلا تُمَسّ ==")
    for w, note in PENDING:
        print("  • %s: %s" % (w, note))
    print("\n== الفصول ==")
    seen = []
    for k in order:
        if secs[k] and secs[k] not in seen:
            seen.append(secs[k]); print("  %-46s ⇐ من %s" % (secs[k], k))
    print("\n== عيّنات ==")
    for k in ("m5", "m11", "m12", "m13"):
        print("\n--- %s (%s) ---\n%s" % (k, secs.get(k, ""), arts[k][:300]))
    assert "الدائرة الإدارية" in arts["m5"] and "20 لسنة 1981" in arts["m5"], "طعنُ م5 مفقود"
    assert "كراهية أو ازدراء أي فئة" in arts["m11"], "البند 11 من م11 مفقود"
    assert "خمسة آلاف دينار" in arts["m12"] and "عشرة آلاف دينار" in arts["m12"], "عقوبةُ م12 مفقودة"
    assert "عشرين ألف دينار" in arts["m13"], "عقوبةُ م13/1 مفقودة"
    assert "مائة ألف دينار" in arts["m7"], "كفالةُ م7 مفقودة"
    assert "خمسمائة ألف دينار" in arts["m3"], "رأسُ مال م3 مفقود"
    print("\n✓ تحقّقاتٌ موضوعية: طعنُ م5 (20/1981)، البندُ 11 من م11 (الكراهية)، عقوبتا م12/م13،")
    print("  كفالةُ م7 (مائة ألف)، رأسُ مال م3 (خمسمائة ألف) — كلُّها ثابتة.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
