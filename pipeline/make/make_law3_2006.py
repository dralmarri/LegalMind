#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""مُحوِّلُ القانون 3/2006 (المطبوعات والنشر) من نصّ الـDOCX إلى JSON مُهيكَل — 33 مادة + ديباجة.
النصُّ النافذ (المعدَّل)، وقد قوبل بصور الجريدة الرسمية (الكويت اليوم ع762، 2/4/2006) وبالنسخة المجمَّعة
المحدَّثة. التصحيحاتُ مستهدَفةٌ حتميّةٌ فقط، كلٌّ منها مؤكَّدٌ من الصور — لا اجتهادَ ولا تخمين."""
import json, pathlib, re, sys

H = pathlib.Path(__file__).parent
RAW = H / "law3_2006_raw.txt"

# (القديم، الجديد، السند) — كلُّها مؤكَّدةٌ بصور الجريدة/النسخة المجمَّعة
FIXES = [
    # علاماتُ فوضى في ترويسات ثلاث مواد (بقايا حواشي الترقيم في الأصل الرقميّ):
    ("المادة 2 )))", "المادة 2", "علامةُ حاشيةٍ التُقطت رموزًا — الصورة: «المادة (2)»"),
    ("المادة 7 )))", "المادة 7", "علامةُ حاشيةٍ التُقطت رموزًا — الصورة: «المادة (7)»"),
    ("المادة 21 )))", "المادة 21", "علامةُ حاشيةٍ التُقطت رموزًا — الصورة: «المادة (21)»"),
    # حرفٌ ساقط (م3): «بعد الحصول عل ترخيص» — الصورة: «على ترخيص»
    ("بعد الحصول عل ترخيص", "بعد الحصول على ترخيص", "حرفٌ ساقط، مؤكَّدٌ من الصورة"),
    # تكرارٌ (dittography) في م5 — الصورة تحمل العبارةَ مرّةً واحدة:
    ("موافقة الوزارة المختصة خلال ستة أشهر من تاريخ بعد موافقة الوزارة المختصة\n"
     "خلال ستة أشهر من تاريخ الوفاة",
     "موافقة الوزارة المختصة خلال ستة أشهر من تاريخ الوفاة",
     "تكرارُ عبارةٍ كاملة (dittography) — الصورة تحملها مرّةً واحدة"),
    # تنوينٌ مضاعف (م7):
    ("ويعاقب وفقاًً لأحكامه", "ويعاقب وفقًا لأحكامه", "تنوينٌ مضاعف"),
    # علامةُ البند الثالث سقطت في قائمة م9 (النصُّ باقٍ كاملًا) — الصورة: «3 – الاسم المقترح…»
    ("ومقر الإدارة.\nالاسم المقترح للصحيفة",
     "ومقر الإدارة.\n3- الاسم المقترح للصحيفة",
     "علامةُ البند (3) ساقطة والنصُّ باقٍ — الصورة تحمل الرقم"),
    # نقطةٌ قفزت قبل السنة (bidi) في م19:
    ("رقم 16 لسنة\n.1960", "رقم 16 لسنة 1960.", "نقطةٌ سبقت السنةَ بأثر ترتيب الاتجاهين"),
    # همزةٌ ساقطة (م21 بند 7):
    ("إفشاء\nسر من شانه", "إفشاء\nسر من شأنه", "همزةٌ ساقطة"),
    # تاءٌ مربوطة (م18):
    ("تنطوي على مخالفه\nلأحكام", "تنطوي على مخالفة\nلأحكام", "هاءٌ بدل تاءٍ مربوطة — الصورة: «مخالفة»"),
    # مسافةٌ زائدة (م21 بند 7):
    ("الأشخاص و حياتهم", "الأشخاص وحياتهم", "مسافةٌ زائدة"),
    # علامةُ البند الأوّل في م27 فقدت شرطتَها (بقيّةُ البنود تحملها) — الصورة: «1 – إذا نشر…»
    ("المؤلف:\n1 إذا نشر في الصحيفة", "المؤلف:\n1- إذا نشر في الصحيفة",
     "شرطةُ البند (1) ساقطة وحدها بين إخوتها — الصورة تحملها"),
    # ألفٌ مقصورة في عنوان الفصل التمهيديّ:
    ("\nفصل تمهيدى\n", "\nفصل تمهيدي\n", "ألفٌ مقصورة بدل الياء"),
]

# مواضعُ تتّفق عليها المصادر فلا تُمَسّ (توثيقٌ فقط):
PENDING = [
    ("م12/1", "«استكمال النقض في الضمان» — والمعنى يقتضي «النقص»؛ لكنّ الصورة والنصَّ الرقميَّ يتّفقان "
              "على «النقض»، فيُترك على حاله ويُوثَّق."),
    ("م12", "«دون حاجة على إجراء آخر» — والمتوقَّع «إلى إجراء آخر»؛ المصدران متّفقان فلا يُمَسّ."),
]

SEC_RE = re.compile(r"^(فصل\s+تمهيد\S*|الفصل\s+\S+|أحكام\s+ختامية|المطبوعات|الصحيفة|"
                    r"المسائل\s+المحظور\s+نشرها.*)$")
ART_RE = re.compile(r"^(?:ال)?مادة\s+(\d+)\s*$")


def main():
    txt = RAW.read_text(encoding="utf-8")
    applied = []
    for old, new, why in FIXES:
        if old in txt:
            txt = txt.replace(old, new, 1); applied.append((old.replace("\n", "⏎")[:48], why))
        elif new in txt:
            applied.append((old.replace("\n", "⏎")[:48], "مطبَّقٌ سلفًا"))
        else:
            print("خطأ: لم يُعثر على موضع التصحيح ولا على بديله:", repr(old[:60])); return 1

    lines = txt.split("\n")
    # الديباجة: من البداية حتى «وافق مجلس الأمة»
    pre_end = next(i for i, l in enumerate(lines) if l.startswith("وافق مجلس الأمة"))
    preamble = " ".join(lines[1:pre_end + 1]).strip()
    title = lines[0] + " " + lines[1] if not lines[1].startswith("بعد") else lines[0]

    arts, order, secs = {}, [], {}
    cur, buf, pending_sec, sec = None, [], None, None
    for l in lines[pre_end + 1:]:
        m = ART_RE.match(l.strip())
        if m:
            if cur:
                arts[cur] = " ".join(buf).strip(); buf = []
            cur = "m" + m.group(1); order.append(cur)
            if pending_sec:
                sec = pending_sec; pending_sec = None
            secs[cur] = sec or ""
            continue
        if SEC_RE.match(l.strip()):
            s = l.strip()
            # أسطرُ العنوان المتتابعة تُضَمّ («الفصل الأول» + «المطبوعات») ما لم تُفصَل بمادة
            pending_sec = (pending_sec + " — " + s) if pending_sec else s
            continue
        if cur:
            buf.append(l.strip())
    if cur:
        arts[cur] = " ".join(buf).strip()

    # توحيدُ علامات البنود «-N» ⇐ «N-» (أثرُ ترتيب الاتجاهين في الأصل الرقميّ)
    for k in arts:
        arts[k] = re.sub(r"(^|\s)-(\d{1,2})(\s)", r"\1\2-\3", arts[k])
        arts[k] = re.sub(r"\s{2,}", " ", arts[k]).strip()

    nums = [int(k[1:]) for k in order]
    assert nums == list(range(1, 34)), "تسلسلٌ مكسور: %r" % nums
    blob = " ".join(arts.values()) + " " + preamble
    assert "�" not in blob and "__" not in blob and ")))" not in blob, "بقايا تلف"
    empty = [k for k, v in arts.items() if len(v) < 15]
    assert not empty, "موادُّ فارغة: %s" % empty

    data = {"title": title, "preamble_text": preamble, "order": order,
            "articles": arts, "sections": secs}
    (H / "law3_2006_parsed.json").write_text(
        json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")

    print("== القانون 3/2006 (المطبوعات والنشر) ==")
    print("المواد: %d (1-33 متسلسلة) | الديباجة: %d حرفًا" % (len(order), len(preamble)))
    print("\n== التصحيحات المطبَّقة (%d) ==" % len(applied))
    for frag, why in applied:
        print("  • «%s…»  ⇐ %s" % (frag, why))
    print("\n== مواضعُ تتّفق عليها المصادر فلا تُمَسّ ==")
    for where, note in PENDING:
        print("  • %s: %s" % (where, note))
    print("\n== الفصول ==")
    seen = []
    for k in order:
        if secs[k] and secs[k] not in seen:
            seen.append(secs[k]); print("  %-42s ⇐ من %s" % (secs[k], k))
    print("\n== عيّنات ==")
    for k in ("m2", "m11", "m19", "m21", "m27"):
        print("\n--- %s (%s) ---\n%s" % (k, secs.get(k, ""), arts[k][:260]))
    # تحقّقاتٌ موضوعية
    assert "المواقع أو الوسائل الإعلامية الإلكترونية" in arts["m2"], "جسرُ م2 للإعلام الإلكتروني مفقود"
    assert "الدائرة\nالإدارية" in arts["m11"] or "الدائرة الإدارية" in arts["m11"], "طعنُ م11 مفقود"
    assert "20 لسنة 1981" in arts["m11"], "إحالةُ م11 إلى 20/1981 مفقودة"
    assert "خمسة آلاف دينار" in arts["m27"] and "عشرين ألف دينار" in arts["m27"], "أرقامُ م27 مفقودة"
    assert "مائة ألف دينار" in arts["m12"], "كفالةُ م12 مفقودة"
    print("\n✓ تحقّقاتٌ موضوعية: جسر م2 الإلكتروني، طعنُ م11 أمام الدائرة الإدارية (20/1981)،")
    print("  أرقامُ عقوبات م27، كفالةُ م12 (مائة ألف) — كلُّها ثابتة.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
