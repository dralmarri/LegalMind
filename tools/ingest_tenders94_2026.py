def _block_text(scope, new_text, kind):
    verb = "النصُّ المضاف" if kind == "add" else "النصُّ المستبدَل"
    head = ("%s — %s — %s — لا يُعمل به إلا %s؛ والنصُّ أعلاه هو النافذ حتى ذلك "
            "التاريخ ـــ" % (BLOCK_MARK, verb, scope, EFFECT_RULE))
    return head + "\n" + new_text


def apply_pending(cur, rid, scope, new_text, anchor, kind, changed_ids):
    cur.execute("""SELECT title, original_text, metadata FROM knowledge_objects
                   WHERE id=%s""", (rid,))
    row = cur.fetchone()
    if not row:
        raise SystemExit("TARGET_MISSING: %s غير موجودة — أوقفت الدفعة." % rid)
    title, text, meta = row[0], row[1], (row[2] or {})

    base = _strip_block(text, BLOCK_MARK)

    # حارس هوية: المتن القائم يجب أن يكون النص المعروف فعلًا، لا نصًّا مجهولًا
    if anchor not in base:
        raise SystemExit("BASE_UNEXPECTED: %s لا يحمل المرساة «%s» — أوقفت الدفعة "
                         "بدل الإلحاق بنصٍّ مجهول." % (rid, anchor))

    # حفظ المتن قبل أي إلحاق — مرة واحدة فقط، فيبقى الأصل مستردًّا حرفيًا
    if "text_before_pending_block" not in meta:
        meta["text_before_pending_block"] = base

    block = _block_text(scope, new_text, kind)
    new_full = base + "\n\n" + block

    new_title = title or ""
    if TITLE_MARK not in new_title:
        new_title = new_title + TITLE_MARK

    meta["pending_amendment"] = {
        "instrument": INSTRUMENT,
        "instrument_id": "legis-94-2026-issue-2" if kind == "add" else "legis-94-2026-issue-1",
        "scope": scope,
        "kind": "addition" if kind == "add" else "substitution",
        "new_text_sha256": _sha(new_text),
        "gazette_ref": GAZETTE_REF,
        "publication_date": GAZETTE_DATE,
        "effective_rule": EFFECT_RULE,
        "effective_from_computed": EFFECT_COMPUTED,
        "effective_from_is_computed": True,
        "in_force_today": False,
        "note": ("النص الجديد مُلحق بالمتن في كتلة موسومة ولم يستبدله، لأن المرسوم "
                 "لا يُعمل به إلا بعد ثلاثة أشهر من النشر. تُطبَّق قاعدة التحديث "
                 "الكاملة (استبدال على المعرّف نفسه + previous_versions) في جولة "
                 "لاحقة بعد بدء النفاذ."),
        "recorded_at": datetime.datetime.now(datetime.timezone.utc).isoformat(),
    }
    if kind != "add":
        # استثناء المادة الثالثة/3: م62 وم62 مكرر تسريان على ما أُعلن قبل النفاذ أيضًا
        if rid in ("legis-49-2016-m62", "legis-49-2016-m62-mukarrar"):
            meta["pending_amendment"]["transitional_note"] = (
                "المادة الثالثة/3 من المرسوم: لا تسري أحكام المادة الأولى على عمليات "
                "الشراء المُعلن عنها قبل النفاذ — **عدا** هذه المادة والمادة (62 مكرر) "
                "أو (62) بحسب الأحوال، فتسريان عليها.")
        else:
            meta["pending_amendment"]["transitional_note"] = (
                "المادة الثالثة/3 من المرسوم: لا تسري أحكام المادة الأولى على عمليات "
                "الشراء التي أُعلن عنها قبل نفاذه (والاستثناء مقصور على المادتين "
                "62 و62 مكرر).")

    if new_full == text and new_title == (title or ""):
        print("  %s — ALREADY_PENDING (بلا تغيير)" % rid)
        return False
    cur.execute("""UPDATE knowledge_objects
                   SET title=%s, original_text=%s, normalized_text=%s,
                       metadata=%s, updated_at=now()
                   WHERE id=%s""",
                (new_title, new_full, normalize_text(new_full), Jsonb(meta), rid))
    changed_ids.append(rid)
    print("  %s — PENDING_BLOCK_SET (%s، +%d حرفًا)"
          % (rid, scope, len(new_full) - len(base)))
    return True


