"""P2.5 — Experiment B2-I: عيّنة واسعة (26 حالة تركيبية) لاختبار الصمود الحتمي — **ليست فقط
الحالات التي كشفت الانحدار الأصلي** (تلك حالة واحدة، m513) كما تشترط المواصفة صراحة. كل حالة:
نص وقائع تركيبي (يُشغَّل ضد `recognize()` الحقيقي المجمَّد لـArm B v1 لإنتاج `scope_queries`
فعليًا لا مصطنعة) + فهرس فصول تركيبي (`chapter_index`) بمجموعات متنافسة على سقف عام واحد.

تصنيف الحالات:
- 6 حالات "بلا تفعيل" (لا مفهوم يُطلَق، scope_queries=[]) — تتحقق أن التصاميم الثلاثة تنحطّ
  بأمان لنفس B عند غياب أي إضافة.
- 4×3=12 حالة "تفعيل مفهوم مفرد" (3 لكل مفهوم من المفاهيم الأربعة) بفهرس فصول مصمَّم عمدًا
  ليضع المجموعة الهادفة عند حافة السقف قبل الحقن، ومجموعة منافسة تُفعَّل فقط برموز `scope_target`
  — إعادة إنتاج عامة لآلية انحدار m513 لا نسخة حرفية منه.
- 4 حالات "تعدد مفاهيم في نص واحد" (تنافس أعلى، فهرس أكبر 8-10 مجموعات).
- 4 حالات "ضغط شديد على السقف" (فهرس كبير، كل المجموعات قريبة الدرجات، تختبر سلوك التعادل)."""

_JUDGE_SCOPE_TOK = "رد قاض عدم صلاحيه نظر دعوى اجراء طلب اثر بطلان حكم صادر"
_CHEQUE1_SCOPE_TOK = "التزام ساحب وفاء قيمه شيك امتناع مسحوب عليه صرف"
_CHEQUE2_SCOPE_TOK = "تقادم دعوى مطالبه قيمه شيك دعوى اثراء بلا سبب سقوط شيك تقادم"
_LINEAGE_SCOPE_TOK = "اختصاص لجنه نسب نظر رفع دعوى نسب اجراء تقديم طلب اثبات نسب نفي لجنه"
_MARITAL_SCOPE_TOK = "عدم سماع دعوى زوجيه انكار استثناء سماع دعوى زوجيه"


def _grp(label, toks, arts):
    return {"label": label, "tokens": set(toks.split()), "arts": arts}


def _base_unrelated_groups():
    """مجموعات خلفية غير مرتبطة، تملأ الفهرس بمنافسة عامة واقعية."""
    return [
        _grp("إيجار", "عين مؤجره اخلاء صيانه مستاجر مالك", [f"rent-m{i}" for i in range(1, 6)]),
        _grp("عمالي", "عامل اجر فصل تعسفي نهايه خدمه", [f"lab-m{i}" for i in range(1, 6)]),
        _grp("جزائي", "جريمه عقوبه حبس سرقه اكراه", [f"crim-m{i}" for i in range(1, 4)]),
        _grp("شركات", "شريك حصه شركه توزيع ارباح", [f"co-m{i}" for i in range(1, 5)]),
    ]


FIXTURES = []

# ---------- 6 حالات بلا تفعيل مفهوم ----------
for i, facts in enumerate([
    "تقدَّم المستأجر بدعوى لإخلاء العين المؤجَّرة بعد امتناع المالك عن الصيانة.",
    "أُدين المتهم بجريمة السرقة وحُكم عليه بالحبس مع الشغل.",
    "رفعت الشركة دعوى تعويض عن أضرار تأخر المقاول في التسليم.",
    "طلب الموظف إلغاء قرار نقله التعسفي إلى إدارة أخرى.",
    "تنازع الشريكان على توزيع أرباح الشركة في نهاية السنة المالية.",
    "أصدرت الجهة الإدارية قرارًا بإلغاء ترخيص المحل التجاري.",
]):
    FIXTURES.append({"id": f"neg-{i+1}", "class": "no_activation", "facts": facts,
                      "chapter_index": _base_unrelated_groups()})

# ---------- 12 حالة: تفعيل مفهوم مفرد (3 لكل مفهوم)، بنمط انحدار m513 المعمَّم ----------
JUDICIAL_FACTS = [
    "القاضي الناظر للدعوى قريب لأحد الخصوم فطلب المحامي رده لعدم صلاحيته.",
    "الدائرة المشكَّلة من ثلاثة قضاة، أحدهم صهر لأحد المتقاضين، وطلب الدفاع رد القاضي.",
    "تبيَّن أن للقاضي مصلحة شخصية في موضوع الدعوى فتقدَّم الخصم بطلب رد فورًا.",
]
CHEQUE_FACTS = [
    "أصدر التاجر شيكًا لصالح المورِّد وامتنع البنك عن صرفه، فيريد المطالبة بقيمته.",
    "ارتد شيك العميل لعدم كفاية الرصيد ويسعى حامله للمطالبة بتحصيل قيمته.",
    "مضت خمس سنوات على تاريخ الشيك ويسأل حامله هل سقطت مطالبته بالتقادم.",
]
LINEAGE_FACTS = [
    "رفعت الأم دعوى لإثبات نسب طفلها إلى والده البيولوجي بعد رفضه الاعتراف به.",
    "يرغب الأب في نفي نسب الطفل عن نفسه عبر دعوى مستقلة أمام المحكمة.",
    "الأخوة يريدون إثبات نسبهم لوالدهم المتوفى ضمن دعوى نسب واحدة.",
]
MARITAL_FACTS = [
    "عقدا زواجًا عرفيًا بينهما، والزوج الآن ينكر وقوع الزواج من الأساس فرفعت دعوى الزوجية.",
    "بعد الخلاف المالي بدأ الزوج بإنكار قيام رابطة الزوجية أصلًا فرفعت دعوى زوجية.",
    "الزوجة أنكرت وقوع عقد الزواج العرفي المدَّعى فرفع دعوى زوجية لإثبات قيامه.",
]

_CONCEPT_TARGETS = [
    ("JUDICIAL", JUDICIAL_FACTS, "قاضي_رد", "قاضي دائره رد صلاحيه قرابه", ["m510", "m511", "m512", "m513", "m514", "m515", "m516"],
     "قاضي_رد_ext", _JUDGE_SCOPE_TOK),
    ("CHEQUE", CHEQUE_FACTS, "شيك_احكام", "شيك ساحب وفاء صرف مسحوب", ["m550", "m551", "m552", "m553", "m554", "m555", "m556"],
     "شيك_ملحق", _CHEQUE1_SCOPE_TOK),
    ("LINEAGE", LINEAGE_FACTS, "نسب_احكام", "نسب اثبات نفي دعوى", ["m600", "m601", "m602", "m603", "m604", "m605", "m606"],
     "نسب_لجنه", _LINEAGE_SCOPE_TOK),
    ("MARITAL", MARITAL_FACTS, "زوجيه_احكام", "زواج زوجيه انكار دعوى", ["m650", "m651", "m652", "m653", "m654", "m655", "m656"],
     "زوجيه_سماع", _MARITAL_SCOPE_TOK),
]

for cname, facts_list, target_label, target_toks, target_arts, comp_label, comp_toks in _CONCEPT_TARGETS:
    for i, facts in enumerate(facts_list):
        # المجموعة الهادفة: تطابق جزئي فقط مع الوقائع (حافة السقف — لا تتصدَّر تلقائيًا)
        target_group = _grp(target_label, target_toks, target_arts)
        # مجموعة منافسة كبيرة تُفعَّل فقط برموز scope_target (محاكاة عامة لانحدار m513:
        # مجموعة جديدة تتصدَّر فقط بعد حقن النطاق فتزاحم الهادفة على السقف)
        competing_group = _grp(comp_label, comp_toks, [f"{comp_label}-x{j}" for j in range(1, 10)])
        # ست مجموعات خلفية إضافية بدرجات متوسطة لضمان بلوغ السقف فعليًا (مخاطرة إزاحة حقيقية)
        filler = [_grp(f"{target_label}_filler{k}", target_toks, [f"{target_label}-f{k}-{j}" for j in range(1, 5)])
                  for k in range(1, 4)]
        chapter_index = [target_group, competing_group] + filler + _base_unrelated_groups()
        FIXTURES.append({"id": f"{cname.lower()}-{i+1}", "class": "single_concept", "facts": facts,
                          "chapter_index": chapter_index, "target_arts": target_arts})

# ---------- 4 حالات: تعدد مفاهيم في نص واحد (تنافس أعلى) ----------
MULTI_FACTS = [
    ("أحد أعضاء الدائرة قريب لأحد أطراف دعوى إثبات نسب منظورة أمامه، وطلب رده لعدم صلاحيته.",
     ["m510", "m511", "m512", "m513"], ["m600", "m601", "m602"]),
    ("زوج القاضية يطالب بقيمة شيك مرتد في نزاع منفصل، والقاضي رُدّ لصلة قرابة بأحد الخصوم.",
     ["m510", "m511", "m512", "m513"], ["m550", "m551", "m552"]),
    ("أنكر الزوج نسب الطفل رغم قيام الزوجية، ورفعت دعوى زوجية ودعوى نسب معًا.",
     ["m650", "m651", "m652"], ["m600", "m601", "m602"]),
    ("موكلي طالب بقيمة شيك مرتد وفي ذات الوقت رفع دعوى إثبات نسب لابنه في قضية أخرى.",
     ["m550", "m551", "m552"], ["m600", "m601", "m602"]),
]
for i, (facts, target_arts_a, target_arts_b) in enumerate(MULTI_FACTS):
    target_a = _grp("هدف_أ", "قاضي دائره رد صلاحيه قرابه شيك ساحب وفاء صرف", target_arts_a)
    target_b = _grp("هدف_ب", "نسب اثبات نفي دعوى زواج زوجيه انكار", target_arts_b)
    comp = _grp("منافس_مشترك", _JUDGE_SCOPE_TOK + " " + _CHEQUE1_SCOPE_TOK + " " + _LINEAGE_SCOPE_TOK,
                [f"multi-comp-{i}-{j}" for j in range(1, 12)])
    chapter_index = [target_a, target_b, comp] + _base_unrelated_groups()
    FIXTURES.append({"id": f"multi-{i+1}", "class": "multi_concept", "facts": facts,
                      "chapter_index": chapter_index, "target_arts": target_arts_a + target_arts_b})

# ---------- 4 حالات: ضغط شديد على السقف (فهرس كبير، درجات متقاربة) ----------
for i in range(4):
    facts = CHEQUE_FACTS[i % 3] if i % 2 == 0 else JUDICIAL_FACTS[i % 3]
    dense_groups = [_grp(f"dense{k}", "شيك قاضي دائره رد صرف ساحب وفاء صلاحيه", [f"dense{i}-m{k}-{j}" for j in range(1, 5)])
                     for k in range(10)]
    target_group = _grp("dense_target", "شيك ساحب وفاء صرف قاضي دائره رد صلاحيه",
                          ["m510", "m511", "m512", "m513", "m550", "m551", "m552", "m553"])
    chapter_index = dense_groups + [target_group] + _base_unrelated_groups()
    FIXTURES.append({"id": f"dense-{i+1}", "class": "cap_pressure", "facts": facts,
                      "chapter_index": chapter_index, "target_arts": ["m510", "m511", "m512", "m513", "m550", "m551", "m552", "m553"]})


if __name__ == "__main__":
    from collections import Counter
    print(f"FIXTURES size = {len(FIXTURES)}")
