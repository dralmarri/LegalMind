import psycopg
from psycopg.types.json import Jsonb
from engine.normalizer.canonical import normalize_text

INSTRUMENT = "المرسوم بقانون رقم %d لسنة %d بإصدار قانون تنظيم القضاء" % (LAWNUM, YEAR)
BRANCH = "إداري"  # مطابق حرفيًا لتصنيف legis-23-1990 الحي في القاعدة


def _row(rid, otype, topic, subtopic, title, text, extra_meta):
    meta = {
        "law_number": LAWNUM, "law_year": YEAR,
        "instrument": INSTRUMENT, "instrument_rank": "مرسوم بقانون",
        "gazette_ref": GAZETTE_REF, "gazette_date": GAZETTE_DATE,
        "upload_origin": "gazette_official_%s" % GAZETTE_DATE,
    }
    meta.update(extra_meta)
    ntext = normalize_text(text)
    return {
        "id": rid, "object_type": otype, "branch": BRANCH,
        "topic": topic, "subtopic": subtopic, "micro_issue": None,
        "title": title, "original_text": text, "normalized_text": ntext,
        "source_key": None, "verification_status": "source_verified",
        "metadata": meta, "authority_status": "source_authority",
        "usable_as_citation": True,
    }


def build_all_records():
    out = []
    # الديباجة
    out.append(_row(
        "legis-%d-%d-preamble" % (LAWNUM, YEAR), "legislation_preamble",
        "مواد الإصدار والديباجة", None,
        "ديباجة %s" % INSTRUMENT, PREAMBLE,
        {"issuing": True, "repeals": "legis-23-1990"},
    ))
    # مواد الإصدار
    for i, (label, text) in enumerate(ISSUING_ARTICLES, start=1):
        out.append(_row(
            "legis-%d-%d-issuing-m%d" % (LAWNUM, YEAR, i), "legislation_issuing_article",
            "مواد الإصدار والديباجة", None,
            "المادة ال%s من مواد الإصدار — %s" % (label, INSTRUMENT), text,
            {"issuing": True, "issuing_seq": i, "issuing_label": label},
        ))
    # مواد القانون
    for topic, subtopic, arts in CHAPTERS:
        for num, text in arts:
            out.append(_row(
                "legis-%d-%d-m%s" % (LAWNUM, YEAR, num), "legislation_article",
                topic, subtopic,
                "مادة %s — قانون تنظيم القضاء (%d/%d)" % (num, LAWNUM, YEAR), text,
                {"issuing": False, "bab": topic, "fasl": subtopic, "article_number": num},
            ))
    return out


def main():
    records = build_all_records()
    assert len(records) == 87, "العدد غير متوقع: %d (المتوقع 87)" % len(records)
    ids = [r["id"] for r in records]
    assert len(ids) == len(set(ids)), "معرفات مكررة!"

    sql = """
        INSERT INTO knowledge_objects
            (id, object_type, branch, topic, subtopic, micro_issue, title,
             original_text, normalized_text, source_key, verification_status,
             metadata, authority_status, usable_as_citation)
        VALUES (%(id)s, %(object_type)s, %(branch)s, %(topic)s, %(subtopic)s,
                %(micro_issue)s, %(title)s, %(original_text)s, %(normalized_text)s,
                %(source_key)s, %(verification_status)s, %(metadata)s,
                %(authority_status)s, %(usable_as_citation)s)
        ON CONFLICT (id) DO UPDATE SET
            object_type = EXCLUDED.object_type, branch = EXCLUDED.branch,
            topic = EXCLUDED.topic, subtopic = EXCLUDED.subtopic,
            micro_issue = EXCLUDED.micro_issue, title = EXCLUDED.title,
            original_text = EXCLUDED.original_text,
            normalized_text = EXCLUDED.normalized_text,
            verification_status = EXCLUDED.verification_status,
            metadata = EXCLUDED.metadata, authority_status = EXCLUDED.authority_status,
            usable_as_citation = EXCLUDED.usable_as_citation,
            updated_at = now()
    """

    dsn = os.environ["DATABASE_URL"]
    with psycopg.connect(dsn) as conn:
        with conn.cursor() as cur:
            for r in records:
                row = dict(r)
                row["metadata"] = Jsonb(row["metadata"])
                cur.execute(sql, row)
            n_ins = cur.rowcount

            # وسم 23/1990 بالإلغاء — النص يبقى محفوظًا كاملًا، لا حذف
            cur.execute("""
                UPDATE knowledge_objects
                SET verification_status = 'superseded',
                    usable_as_citation = false,
                    metadata = metadata || %s::jsonb,
                    updated_at = now()
                WHERE id LIKE 'legis-23-1990-%%'
            """, (json.dumps({
                "repealed_by": "legis-%d-%d" % (LAWNUM, YEAR),
                "repeal_instrument": INSTRUMENT,
                "repeal_date": GAZETTE_DATE,
                "repeal_gazette_ref": GAZETTE_REF,
            }),))
            n_repealed = cur.rowcount
            assert n_repealed == 82, "عدد الموسومة بالإلغاء غير متوقع: %d (المتوقع 82)" % n_repealed
        conn.commit()

    print("INGEST_OK: %d كائنًا أُدخل/حُدِّث، %d كائنًا من 23/1990 وُسم بالإلغاء" % (len(records), n_repealed))

    # تحقق فوري
    with psycopg.connect(dsn) as conn:
        with conn.cursor() as cur:
            cur.execute("SELECT count(*) FROM knowledge_objects WHERE id LIKE %s", ("legis-%d-%d-%%" % (LAWNUM, YEAR),))
            n_new = cur.fetchone()[0]
            cur.execute("""SELECT count(*) FROM knowledge_objects
                           WHERE id LIKE 'legis-23-1990-%%' AND verification_status = 'superseded'""")
            n_sup = cur.fetchone()[0]
            print("تحقق: legis-%d-%d = %d كائنًا (متوقع 87) | 23/1990 الموسومة = %d (متوقع 82)"
                  % (LAWNUM, YEAR, n_new, n_sup))
            assert n_new == 87
            assert n_sup == 82

    print("VERIFY_OK")


